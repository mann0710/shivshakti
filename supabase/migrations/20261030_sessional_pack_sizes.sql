-- Sessional items: one row per item with a per-kg / per-litre / per-piece rate.
-- Pack sizes (250 g, 500 g, 750 g, 1 kg + custom) are calculated from the rate instead of stored as extra rows.
-- Safe to run more than once. Run in Supabase -> SQL Editor, then open Sessional Items -> "Merge duplicates".

alter table seasonal_items add column if not exists unit text;
alter table seasonal_items add column if not exists rate numeric(12,2);
alter table seasonal_items add column if not exists pack_sizes jsonb;   -- e.g. [250, 500, 750, 1000]; null = shop defaults
alter table seasonal_items add column if not exists pack_prices jsonb;  -- manual price per size, e.g. {"250": 130}
alter table seasonal_items add column if not exists category text;      -- Sweets, Namkeen, Dry Fruits...

-- Old rows: derive the unit and per-kg / per-litre rate from the stored pack.
update seasonal_items
   set unit = case when weight_unit = 'ltr' then 'ltr' else 'kg' end
 where unit is null;
update seasonal_items
   set rate = round(price * 1000.0 / nullif(weight, 0), 2)
 where rate is null and unit in ('kg', 'ltr');
update seasonal_items set rate = price where rate is null;

alter table seasonal_items alter column unit set default 'kg';
alter table seasonal_items alter column unit set not null;
alter table seasonal_items drop constraint if exists seasonal_items_unit_check;
alter table seasonal_items add constraint seasonal_items_unit_check check (unit in ('kg', 'ltr', 'pc'));

-- Shop-wide default pack sizes, e.g. {"kg": [250, 500, 750, 1000], "ltr": [250, 500, 1000], "pc": [1]}
alter table data_center add column if not exists pack_sizes jsonb;

-- Running bill numbers for counter sales (existing bills are numbered in creation order).
alter table seasonal_orders add column if not exists bill_no bigint generated by default as identity;

create index if not exists seasonal_orders_year_idx on seasonal_orders (year);
create index if not exists seasonal_preorders_year_idx on seasonal_preorders (year);

-- Reload the API schema cache so the app sees the new columns immediately.
notify pgrst, 'reload schema';
